def render_glossary(cols: list):
    """주어진 컬럼 리스트 중 글로서리에 등록된 것만 골라 expander로 표시"""
    entries = [(c, STAT_GLOSSARY[c]) for c in dict.fromkeys(cols) if c in STAT_GLOSSARY]
    if not entries:
        return
    with st.expander("📖 이 페이지에서 쓰이는 용어 설명 (처음 보는 용어가 있다면 클릭)"):
        for col, (kor_name, desc) in entries:
            st.markdown(f"**{kor_name}** (`{col}`) — {desc}")
